// Scans public/ for raster + svg assets and writes app/work/image-dims.ts
// with intrinsic { width, height } for each, so <Image> can reserve exact
// space from the real aspect ratio (no fixed-height boxes, no upscaling).
// Run: npm run gen:dims
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const PUBLIC = join(process.cwd(), 'public');
const OUT = join(process.cwd(), 'app', 'work', 'image-dims.ts');
const EXT = /\.(png|jpe?g|webp|gif|svg)$/i;

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (EXT.test(name)) out.push(full);
  }
  return out;
}

function pngSize(buf) {
  if (buf.readUInt32BE(0) !== 0x89504e47) return null;
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

function gifSize(buf) {
  if (buf.toString('ascii', 0, 3) !== 'GIF') return null;
  return { width: buf.readUInt16LE(6), height: buf.readUInt16LE(8) };
}

function webpSize(buf) {
  if (buf.toString('ascii', 0, 4) !== 'RIFF' || buf.toString('ascii', 8, 12) !== 'WEBP') return null;
  const fmt = buf.toString('ascii', 12, 16);
  if (fmt === 'VP8 ') return { width: buf.readUInt16LE(26) & 0x3fff, height: buf.readUInt16LE(28) & 0x3fff };
  if (fmt === 'VP8L') {
    const b = buf.readUInt32LE(21);
    return { width: (b & 0x3fff) + 1, height: ((b >> 14) & 0x3fff) + 1 };
  }
  if (fmt === 'VP8X') return { width: (buf.readUIntLE(24, 3) & 0xffffff) + 1, height: (buf.readUIntLE(27, 3) & 0xffffff) + 1 };
  return null;
}

function jpegSize(buf) {
  if (buf[0] !== 0xff || buf[1] !== 0xd8) return null;
  let o = 2;
  while (o < buf.length) {
    if (buf[o] !== 0xff) { o++; continue; }
    const marker = buf[o + 1];
    if (marker === 0xd8 || marker === 0xd9 || (marker >= 0xd0 && marker <= 0xd7)) { o += 2; continue; }
    const len = buf.readUInt16BE(o + 2);
    if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
      return { height: buf.readUInt16BE(o + 5), width: buf.readUInt16BE(o + 7) };
    }
    o += 2 + len;
  }
  return null;
}

function svgSize(text) {
  const tag = text.match(/<svg[^>]*>/i)?.[0] ?? '';
  const vb = tag.match(/viewBox\s*=\s*["']\s*[-\d.]+\s+[-\d.]+\s+([\d.]+)\s+([\d.]+)/i);
  if (vb) return { width: Math.round(+vb[1]), height: Math.round(+vb[2]) };
  const w = tag.match(/\bwidth\s*=\s*["']?([\d.]+)/i);
  const h = tag.match(/\bheight\s*=\s*["']?([\d.]+)/i);
  if (w && h) return { width: Math.round(+w[1]), height: Math.round(+h[1]) };
  return null;
}

function size(file) {
  const buf = readFileSync(file);
  if (/\.svg$/i.test(file)) return svgSize(buf.toString('utf8'));
  return pngSize(buf) || jpegSize(buf) || webpSize(buf) || gifSize(buf);
}

const entries = [];
for (const file of walk(PUBLIC).sort()) {
  const key = '/' + relative(PUBLIC, file).split(sep).join('/');
  const dim = size(file);
  if (dim && dim.width && dim.height) entries.push([key, dim.width, dim.height]);
  else console.warn('skipped (no dimensions):', key);
}

const body = entries.map(([k, w, h]) => `  ${JSON.stringify(k)}: [${w}, ${h}],`).join('\n');
writeFileSync(OUT, `// AUTO-GENERATED by scripts/gen-image-dims.mjs — run \`npm run gen:dims\` after changing assets.\nexport const imageDims: Record<string, readonly [number, number]> = {\n${body}\n};\n\nexport function imgDims(src: string): { width: number; height: number } | null {\n  const d = imageDims[src];\n  return d ? { width: d[0], height: d[1] } : null;\n}\n`);
console.log(`wrote ${entries.length} entries -> ${relative(process.cwd(), OUT)}`);
